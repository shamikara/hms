-- ----------------------------------------------------------------------------
-- C1. Rating domain: every star rating is an integer 1..5.
--     Enforced in the DB as well as in Zod so a bad API caller cannot poison
--     the rating aggregates.
-- ----------------------------------------------------------------------------
ALTER TABLE "SafariReview"
  ADD CONSTRAINT "SafariReview_ratings_range_check" CHECK (
    "overallRating"         BETWEEN 1 AND 5
    AND "driverOverall"         BETWEEN 1 AND 5
    AND "driverSafety"          BETWEEN 1 AND 5
    AND "driverPunctuality"     BETWEEN 1 AND 5
    AND "driverProfessionalism" BETWEEN 1 AND 5
    AND "driverCommunication"   BETWEEN 1 AND 5
    AND ("driverKnowledge" IS NULL OR "driverKnowledge" BETWEEN 1 AND 5)
    AND "vehicleOverall"     BETWEEN 1 AND 5
    AND "vehicleCleanliness" BETWEEN 1 AND 5
    AND "vehicleComfort"     BETWEEN 1 AND 5
    AND "vehicleCondition"   BETWEEN 1 AND 5
    AND "vehicleRideQuality" BETWEEN 1 AND 5
    AND "vehicleSuitability" BETWEEN 1 AND 5
  );


-- ----------------------------------------------------------------------------
-- C4. OVERLAP PREVENTION (the important one).
--     The application layer re-checks conflicts inside a SERIALIZABLE-ish
--     transaction, but two concurrent dispatchers can still interleave between
--     the check and the insert. These EXCLUDE constraints make the database
--     itself refuse a second active trip for the same vehicle or driver whose
--     scheduled window overlaps an existing one.
--
--     Cancelled trips are excluded from the constraint so a cancelled slot can
--     be re-used immediately.
-- ----------------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS btree_gist;

ALTER TABLE "SafariTrip"
  ADD CONSTRAINT "SafariTrip_vehicle_no_overlap" EXCLUDE USING gist (
    "vehicleId" WITH =,
    tsrange("scheduledStart", "scheduledEnd", '[)') WITH &&
  ) WHERE ("status" <> 'CANCELLED'::"SafariTripStatus");

ALTER TABLE "SafariTrip"
  ADD CONSTRAINT "SafariTrip_driver_no_overlap" EXCLUDE USING gist (
    "driverId" WITH =,
    tsrange("scheduledStart", "scheduledEnd", '[)') WITH &&
  ) WHERE ("status" <> 'CANCELLED'::"SafariTripStatus");

-- A guide cannot lead two overlapping trips either. Nullable guideId rows are
-- skipped automatically: NULL never conflicts under an EXCLUDE constraint.
ALTER TABLE "SafariTrip"
  ADD CONSTRAINT "SafariTrip_guide_no_overlap" EXCLUDE USING gist (
    "guideId" WITH =,
    tsrange("scheduledStart", "scheduledEnd", '[)') WITH &&
  ) WHERE ("status" <> 'CANCELLED'::"SafariTripStatus" AND "guideId" IS NOT NULL);

